package dev.rakshit.repair.pr;

import dev.rakshit.repair.agent.RepairRun;
import dev.rakshit.repair.patch.UnifiedDiff;
import java.util.List;
import java.util.Map;

/** Renders the pull-request description: what failed, where the agent looked, what it changed, and how that was verified. */
public final class PrBody {
    private PrBody() {}

    public static String title(RepairRun r) {
        List<String> f = r.failingTests();
        String first = f.isEmpty() ? "failing tests" : f.get(0).replaceFirst(":.*$", "");
        return "Fix " + first + (f.size() > 1 ? " (+" + (f.size() - 1) + " more)" : "");
    }

    @SuppressWarnings("unchecked")
    public static String render(RepairRun r) {
        StringBuilder sb = new StringBuilder();
        sb.append("## Summary\n\n").append(r.rationale().isBlank() ? "Automated fix." : r.rationale()).append("\n\n");
        sb.append("**Failing before:** ").append(String.join(", ", r.failingTests())).append("\n\n");

        sb.append("## Where the bug was found\n\n");
        sb.append("| # | Method | Score | Spectrum | Stack frame | Proximity | Text |\n|---|---|---|---|---|---|---|\n");
        int shown = 0;
        for (Map<String, Object> s : r.suspects()) {
            if (shown++ == 3) break;
            Map<String, Object> sig = (Map<String, Object>) s.get("signals");
            sb.append(String.format("| %s | `%s` | %.2f | %.2f | %.2f | %.2f | %.2f |%n", s.get("rank"), s.get("label"),
                    ((Number) s.get("score")).doubleValue(), ((Number) sig.get("spectrum")).doubleValue(),
                    ((Number) sig.get("frame")).doubleValue(), ((Number) sig.get("proximity")).doubleValue(),
                    ((Number) sig.get("text")).doubleValue()));
        }
        sb.append("\nSpectrum = how strongly the failing (and not the passing) tests reach the method through the call graph; ")
                .append("frame = position in the stack trace; proximity = call distance from the test; text = BM25 + vector match with the failure.\n\n");

        sb.append("## Change\n\n");
        int[] st = UnifiedDiff.stats(r.diff());
        sb.append(st[0]).append(" line(s) added, ").append(st[1]).append(" removed.\n\n```diff\n").append(r.diff()).append("```\n\n");
        if (!r.acceptedPartials().isEmpty()) {
            sb.append("Built up over several rounds:\n");
            for (String p : r.acceptedPartials()) sb.append("- ").append(p).append('\n');
            sb.append('\n');
        }

        sb.append("## Blast radius\n\n");
        Map<String, Object> blast = r.blast();
        List<Object> up = blast.get("upstream") instanceof List<?> l ? (List<Object>) l : List.of();
        List<Object> tests = blast.get("tests") instanceof List<?> l ? (List<Object>) l : List.of();
        sb.append("Changed method(s) are called, directly or indirectly, by ").append(up.size()).append(" other method(s) and exercised by ")
                .append(tests.size()).append(" test(s).\n");
        for (int i = 0; i < Math.min(8, up.size()); i++) sb.append("- `").append(up.get(i)).append("`\n");
        sb.append('\n');

        sb.append("## Verification\n\n");
        sb.append("- Sandbox: ").append(r.sandbox()).append('\n');
        sb.append("- Before: ").append(r.failingTests().size()).append(" failing, ").append(r.baselinePassing()).append(" passing.\n");
        sb.append("- After the final diff, applied to a clean checkout: all tests pass, none of the previously passing tests regressed, no new compiler warnings.\n");
        sb.append("- Candidates verified: ").append(r.attempts().size()).append(" over ").append(r.round()).append(" round(s).\n\n");

        sb.append("## Telemetry\n\n");
        sb.append(String.format("- Latency %.1f s, %d sandbox runs", r.latencyMs() / 1000.0, r.sandboxRuns()));
        if (r.usage().calls() > 0) {
            sb.append(String.format(", %d model call(s), %d input / %d output tokens, about $%.4f", r.usage().calls(),
                    r.usage().inputTokens(), r.usage().outputTokens(), r.costUsd()));
        } else {
            sb.append(", no model calls");
        }
        sb.append("\n\n---\nGenerated by agentic-bug-repair. A person should review this before it is merged.\n");
        return sb.toString();
    }
}
